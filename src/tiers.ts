import { existsSync } from 'node:fs';
import { join } from 'node:path';

export type Tier = 'brain' | 'careful' | 'mechanical';
export type FileSpec = { rel: string; next: (cur: string) => string; owned?: (cur: string) => boolean };
export type Provider = { id: 'claude' | 'codex'; detect(home: string): boolean; models: Record<Tier, string>; files(o: { home: string; guard: string | null }): FileSpec[] };

export const HANDS = ['hands-careful', 'hands-mechanical'] as const;

const LANE = `You are a hand: the brain plans, you execute.

- Do exactly what the brain's spec says. Never choose scope, architecture or approach.
- Report what changed and the real output of the verification you ran.
- If the spec is wrong, ambiguous or blocked, stop and say so. Do not improvise.`;

const DESC: Record<'careful' | 'mechanical', string> = {
  careful: 'Careful hands: implements a designed change, writes tests, fixes a diagnosed bug. Receives a fully specified task from the brain.',
  mechanical: 'Mechanical hands: renames, pattern edits, boilerplate, running commands and reporting output. Receives a fully specified task from the brain.',
};

export const TIER_RULES = `- The brain plans, reads and verifies. It never edits files.
- Careful hands do designed changes, tests and diagnosed fixes.
- Mechanical hands do renames, pattern edits, boilerplate and running commands.
- A dispatch names the files, the change and how to verify it.
- Hands push back when the spec is wrong.`;

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === 'object' && v !== null && !Array.isArray(v);
const parseObj = (cur: string): Obj | null => {
  if (cur.trim() === '') return {};
  try {
    const v: unknown = JSON.parse(cur);
    return isObj(v) ? v : null;
  } catch {
    return null;
  }
};
const validJson = (cur: string): boolean => parseObj(cur) !== null;

// Edits a JSON object; returns the input text untouched when the edit changes nothing.
const jsonMerge = (cur: string, edit: (o: Obj) => boolean): string => {
  const o = parseObj(cur);
  return o !== null && edit(o) ? `${JSON.stringify(o, null, 2)}\n` : cur;
};

// Adds a PreToolUse entry unless one already runs this exact command.
const addGuard = (o: Obj, matcher: string, command: string): boolean => {
  const hooks = o.hooks === undefined ? (o.hooks = {} as Obj) : o.hooks;
  if (!isObj(hooks)) return false;
  const pre = hooks.PreToolUse === undefined ? (hooks.PreToolUse = [] as unknown[]) : hooks.PreToolUse;
  if (!Array.isArray(pre)) return false;
  const has = pre.some((e) => isObj(e) && Array.isArray(e.hooks) && e.hooks.some((h) => isObj(h) && h.command === command));
  if (has) return false;
  pre.push({ matcher, hooks: [{ type: 'command', command }] });
  return true;
};

const claudeAgent = (tier: 'careful' | 'mechanical', model: string): FileSpec => ({
  rel: `.claude/agents/hands-${tier}.md`,
  next: () => `---\nname: hands-${tier}\ndescription: ${DESC[tier]}\nmodel: ${model}\n---\n\n${LANE}\n`,
  owned: (cur) => cur.startsWith('---\nname: hands-'),
});

const codexAgent = (tier: 'careful' | 'mechanical', model: string): FileSpec => ({
  rel: `.codex/agents/hands-${tier}.toml`,
  next: () => `# hive: generated by hive-collab-context\nname = "hands-${tier}"\ndescription = "${DESC[tier]}"\nmodel = "${model}"\ndeveloper_instructions = """\n${LANE}\n"""\n`,
  owned: (cur) => cur.includes('# hive:'),
});

const hasTopModel = (toml: string): boolean => {
  for (const l of toml.split('\n')) {
    if (/^\s*\[/.test(l)) return false;
    if (/^\s*model\s*=/.test(l)) return true;
  }
  return false;
};

// ponytail: Codex slugs are pinned per release; a new Hive release updates them
export const PROVIDERS: Provider[] = [
  {
    id: 'claude',
    detect: (home) => existsSync(join(home, '.claude')),
    models: { brain: 'opus', careful: 'sonnet', mechanical: 'haiku' },
    files: ({ guard }) => [
      claudeAgent('careful', 'sonnet'),
      claudeAgent('mechanical', 'haiku'),
      {
        rel: '.claude/settings.local.json',
        next: (cur) =>
          jsonMerge(cur, (o) => {
            let changed = false;
            if (!('model' in o)) [o.model, changed] = ['opus', true];
            if (guard !== null && addGuard(o, 'Edit|Write|NotebookEdit|MultiEdit|Bash', guard)) changed = true;
            return changed;
          }),
        owned: validJson,
      },
    ],
  },
  {
    id: 'codex',
    detect: (home) => existsSync(join(home, '.codex')),
    models: { brain: 'gpt-6.2-sol', careful: 'gpt-6.1-terra', mechanical: 'gpt-6-luna' },
    files: ({ guard }) => [
      codexAgent('careful', 'gpt-6.1-terra'),
      codexAgent('mechanical', 'gpt-6-luna'),
      { rel: '.codex/config.toml', next: (cur) => (hasTopModel(cur) ? cur : `model = "gpt-6.2-sol"\n${cur}`) },
      ...(guard === null
        ? []
        : [{ rel: '.codex/hooks.json', next: (cur: string) => jsonMerge(cur, (o) => addGuard(o, '^(Bash|apply_patch)$', guard)), owned: validJson }]),
    ],
  },
];

export function guardCommand(p: Provider, home: string): string {
  const path = join(home, '.hive', 'bin', 'guard.mjs');
  const hands = p.id === 'claude' ? HANDS.join(',') : `${p.models.careful},${p.models.mechanical}`;
  return `node ${/\s/.test(path) ? `"${path}"` : path} ${p.id} ${hands}`;
}
